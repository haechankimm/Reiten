function getLang() {
  try {
    const l = localStorage.getItem(LANG_KEY);
    return LANGS.includes(l) ? l : "ko";
  } catch (e) {
    return "ko";
  }
}

function setLang(lang) {
  if (!LANGS.includes(lang) || lang === getLang()) return;
  try { localStorage.setItem(LANG_KEY, lang); } catch (e) {}
  location.reload();
}

